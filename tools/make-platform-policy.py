#!/usr/bin/env python3
"""Write platforms/codex/AGENTS.kit.md, the Codex CLI policy file, generated from POLICY.md.

Codex reads one instruction file capped at 32 KiB, so the output is the platform's own text (PLATFORM.md), then the
POLICY.md sections named in policy.sections copied verbatim, then an index that points at every other section. The
first line carries the kit version from line 3 of POLICY.md. Output is deterministic: UTF-8, LF line endings.
"""
import argparse
import itertools
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_DIR = os.path.join(ROOT, "platforms", "codex")
OUTPUT = "AGENTS.kit.md"
LIMIT = 16384
VERSION_RE = re.compile(r"Claude Usage Optimizer version: (\d{4}-\d{2}-\d{2}\.\d+)")
HEADER = ("<!-- Claude Usage Optimizer {version} for Codex CLI; generated by tools/make-platform-policy.py from POLICY.md;"
          " do not edit -->\n")
INDEX_TITLE = "## The rest of the policy\n"
INDEX_LINE = "- {}: read that section of `~/.claude/usage-optimizer/POLICY.md` before work it covers.\n"


class PolicyError(Exception):
    pass


def read_text(path):
    # Universal newlines: a CRLF checkout reads as LF, so the output never depends on the machine.
    with open(path, encoding="utf-8") as stream:
        return stream.read()


def as_lines(text):
    parts = text.split("\n")
    if parts and parts[-1] == "":
        parts.pop()
    return [part + "\n" for part in parts]


def ensure_blank_line_after(text):
    """Platform text ends with a blank line, so the first POLICY.md section starts a new block."""
    if not text:
        return text
    text = text if text.endswith("\n") else text + "\n"
    return text if text.endswith("\n\n") else text + "\n"


def level_two_spans(lines):
    """Return (heading, start, end) for each '## ' section; a section ends before the next '## ' line."""
    starts = [index for index, line in enumerate(lines) if line.startswith("## ")]
    spans = []
    for position, start in enumerate(starts):
        end = starts[position + 1] if position + 1 < len(starts) else len(lines)
        spans.append((lines[start].rstrip("\n"), start, end))
    return spans


def build(policy_path, platform_dir):
    lines = as_lines(read_text(policy_path))
    version_line = lines[2].rstrip("\n") if len(lines) > 2 else ""
    match = VERSION_RE.search(version_line)
    if not match:
        raise PolicyError("{}: line 3 has no 'Claude Usage Optimizer version: <date>' version".format(policy_path))
    version = match.group(1)

    spans = level_two_spans(lines)
    listed = []
    wanted = [line for line in read_text(os.path.join(platform_dir, "policy.sections")).split("\n") if line]
    for heading in wanted:
        found = [span for span in spans if span[0] == heading]
        if not found:
            raise PolicyError("heading not in POLICY.md: {}".format(ascii(heading)))
        if len(found) > 1:
            raise PolicyError("heading occurs {} times in POLICY.md: {}".format(len(found), ascii(heading)))
        listed.append(found[0])

    platform = ensure_blank_line_after(read_text(os.path.join(platform_dir, "PLATFORM.md")))
    parts = [HEADER.format(version=version), platform]
    for _, start, end in listed:
        parts.append("".join(lines[start:end]))
    body = "".join(parts)
    if not body.endswith("\n\n"):
        body += "\n"
    listed_headings = {heading for heading, _, _ in listed}
    index = [INDEX_TITLE, "\n"]
    index.extend(INDEX_LINE.format(heading[3:]) for heading, _, _ in spans if heading not in listed_headings)
    data = (body + "".join(index)).encode("utf-8")
    if len(data) > LIMIT:
        raise PolicyError("generated output is {} bytes, over the {} byte limit".format(len(data), LIMIT))
    return data


def check(path, data):
    try:
        with open(path, "rb") as stream:
            current = stream.read()
    except OSError:
        print("missing {}; run tools/make-platform-policy.py".format(path))
        return 1
    if current == data:
        return 0
    wanted_lines = data.decode("utf-8").split("\n")
    current_lines = current.decode("utf-8", errors="replace").split("\n")
    for number, (want, have) in enumerate(itertools.zip_longest(wanted_lines, current_lines), 1):
        if want != have:
            print("{} differs from POLICY.md at line {}: generated {}, file has {}; run tools/make-platform-policy.py"
                  .format(path, number, ascii(want), ascii(have)))
            return 1
    return 1


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", default=os.path.join(ROOT, "POLICY.md"))
    parser.add_argument("--dir", default=DEFAULT_DIR,
                        help="holds PLATFORM.md and policy.sections; %s is written here" % OUTPUT)
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 and name the first difference")
    args = parser.parse_args(argv)
    try:
        data = build(args.policy, args.dir)
    except (PolicyError, OSError) as error:
        print("make-platform-policy: {}".format(error), file=sys.stderr)
        return 1
    path = os.path.join(args.dir, OUTPUT)
    if args.check:
        return check(path, data)
    with open(path, "wb") as stream:
        stream.write(data)
    print("wrote {} ({} bytes)".format(path, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
