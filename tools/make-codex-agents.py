#!/usr/bin/env python3
"""Write Codex CLI agent roles from explore.codex_subagents in arms.json.

Each role becomes platforms/codex/agents/<name>.toml. The model id is lanes.<lane>.model at generation
time. developer_instructions is a TOML literal string. With --check, write nothing and exit 1 on any difference.
"""
import argparse
import glob
import json
import os
import re
import sys

try:
    import tomllib
except ImportError:
    tomllib = None

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VERSION_RE = re.compile(r"Coding Tool Optimizer version: (\d{4}-\d{2}-\d{2}\.\d+)")
COMMENT = "# generated by tools/make-codex-agents.py; Coding Tool Optimizer {version}\n"
REQUIRED = ("name", "lane", "effort", "description", "may_spawn")


class CatalogError(Exception):
    pass


def kit_version(policy_path):
    """The kit version on line 3 of POLICY.md, the same line make-platform-policy.py reads."""
    with open(policy_path, encoding="utf-8") as stream:
        lines = stream.read().splitlines()
    version_line = lines[2] if len(lines) > 2 else ""
    match = VERSION_RE.search(version_line)
    if not match:
        raise CatalogError("{}: line 3 has no 'Coding Tool Optimizer version: <date>' version".format(policy_path))
    return match.group(1)


def basic_string(value):
    """A TOML basic string. Descriptions and model ids need no escape; quotes and backslashes do."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def instructions_for(role):
    """What the role is for, what it may spawn, and how it reports."""
    if "read-only" in role["description"].lower():
        access = "You are read-only. Never edit files."
    else:
        access = "Edit only the files the brief names."
    allowed = role["may_spawn"]
    if not allowed:
        spawn = "You spawn nothing."
    else:
        spawn = "You may spawn only {}.".format(", ".join(allowed))
    return (
        "You are {name}, a Codex sub-agent for the Coding Tool Optimizer kit.\n"
        "You are for {description}.\n"
        "{access}\n"
        "{spawn} Never spawn astra.\n"
        "Take a fresh brief. Never take the parent's full context.\n"
        "Return at most 60 lines. Put [OBSERVED path:line] or [INFERRED] on each claim.\n"
    ).format(name=role["name"], description=role["description"], access=access, spawn=spawn)


def render(role, model, version):
    body = instructions_for(role)
    if "'''" in body or "\r" in body:
        raise CatalogError("{}: instructions cannot be a TOML literal string".format(role["name"]))
    parts = [
        COMMENT.format(version=version),
        "name = {}\n".format(basic_string(role["name"])),
        "description = {}\n".format(basic_string(role["description"])),
        "model = {}\n".format(basic_string(model)),
        "model_reasoning_effort = {}\n".format(basic_string(role["effort"])),
        "developer_instructions = '''\n",
        body,
        "'''\n",
    ]
    return "".join(parts)


def roles_from(data):
    explore = data.get("explore") if isinstance(data, dict) else None
    roles = explore.get("codex_subagents") if isinstance(explore, dict) else None
    if not isinstance(roles, list) or not roles:
        raise CatalogError("arms.json explore.codex_subagents must be a non-empty list")
    lanes = data.get("lanes")
    if not isinstance(lanes, dict):
        raise CatalogError("arms.json has no lanes object")
    names = []
    for role in roles:
        if not isinstance(role, dict) or any(key not in role for key in REQUIRED):
            raise CatalogError("a Codex role is missing one of {}".format(", ".join(REQUIRED)))
        name = role["name"]
        if not isinstance(name, str) or not name or "/" in name or "\\" in name or name != name.strip():
            raise CatalogError("role name is not a single path segment: {}".format(name))
        if name in names:
            raise CatalogError("duplicate Codex role: {}".format(name))
        names.append(name)
        lane = role["lane"]
        lane_row = lanes.get(lane) if isinstance(lane, str) else None
        model = lane_row.get("model") if isinstance(lane_row, dict) else None
        if not isinstance(model, str) or not model:
            raise CatalogError("{}: no model for lane {}".format(name, lane))
        if lane == "astra" or model == lanes.get("astra", {}).get("model"):
            raise CatalogError("{}: astra is never a sub-agent".format(name))
        if not isinstance(role["effort"], str) or not role["effort"]:
            raise CatalogError("{}: effort must be a string".format(name))
        if not isinstance(role["description"], str) or not role["description"]:
            raise CatalogError("{}: description must be a string".format(name))
        may_spawn = role["may_spawn"]
        if not isinstance(may_spawn, list) or any(not isinstance(item, str) for item in may_spawn):
            raise CatalogError("{}: may_spawn must be a list of role names".format(name))
    for role in roles:
        unknown = [item for item in role["may_spawn"] if item not in names]
        if unknown:
            raise CatalogError("{}: may_spawn names an unknown role: {}".format(role["name"], ", ".join(unknown)))
    return roles


def wanted(arms_path, policy_path):
    with open(arms_path, encoding="utf-8") as stream:
        data = json.load(stream)
    version = kit_version(policy_path)
    lanes = data["lanes"]
    files = {}
    for role in roles_from(data):
        model = lanes[role["lane"]]["model"]
        text = render(role, model, version)
        validate(text, role["name"])
        files[role["name"] + ".toml"] = text
    return files


def validate(text, name):
    """Parse the file when this Python has tomllib (3.11+)."""
    if tomllib is None:
        return
    try:
        parsed = tomllib.loads(text)
    except tomllib.TOMLDecodeError as error:
        raise CatalogError("{}: invalid TOML: {}".format(name, error))
    for key in ("name", "description", "model", "model_reasoning_effort", "developer_instructions"):
        if not isinstance(parsed.get(key), str) or not parsed[key]:
            raise CatalogError("{}: missing {}".format(name, key))


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--arms", default=os.path.join(ROOT, "arms.json"))
    parser.add_argument("--policy", default=os.path.join(ROOT, "POLICY.md"))
    parser.add_argument("--out", default=os.path.join(ROOT, "platforms", "codex", "agents"))
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 on any difference")
    args = parser.parse_args(argv)
    try:
        files = wanted(args.arms, args.policy)
    except (CatalogError, OSError, ValueError) as error:
        print("make-codex-agents: {}".format(error), file=sys.stderr)
        return 1
    existing = {os.path.basename(path) for path in glob.glob(os.path.join(args.out, "kit-*.toml"))}
    differences = []
    for name, text in files.items():
        path = os.path.join(args.out, name)
        try:
            with open(path, encoding="utf-8", newline="") as stream:
                current = stream.read()
        except OSError:
            current = None
        if current != text:
            differences.append(("write" if current is None else "update", name))
            if not args.check:
                os.makedirs(args.out, exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as stream:
                    stream.write(text)
    for name in sorted(existing - set(files)):
        differences.append(("remove", name))
        if not args.check:
            os.unlink(os.path.join(args.out, name))
    for action, name in differences:
        print("{}{} {}".format("would " if args.check else "", action, name))
    return 1 if args.check and differences else 0


if __name__ == "__main__":
    sys.exit(main())
