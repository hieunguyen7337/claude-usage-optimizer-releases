import os
import re
import shutil
import subprocess
import sys
import tempfile
import unittest


ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOL = os.path.join(ROOT, "tools", "make-platform-policy.py")
REAL_POLICY = os.path.join(ROOT, "POLICY.md")
REAL_DIR = os.path.join(ROOT, "platforms", "codex")
SECTIONS = "## Routing, in order\n## Invariants (every lane)\n## Briefs\n## Data\n"
PLATFORM = "# Claude Usage Optimizer on Codex CLI\n\nThe main session writes this file; the generator includes whatever it holds.\n"


def read(path):
    with open(path, encoding="utf-8") as stream:
        return stream.read()


def write(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as stream:
        stream.write(text)


class PlatformPolicyTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.dir = os.path.join(self.temp.name, "codex")
        os.makedirs(self.dir)
        self.policy = os.path.join(self.temp.name, "POLICY.md")
        shutil.copyfile(REAL_POLICY, self.policy)
        write(os.path.join(self.dir, "policy.sections"), SECTIONS)
        write(os.path.join(self.dir, "PLATFORM.md"), PLATFORM)
        self.output = os.path.join(self.dir, "AGENTS.kit.md")

    def tearDown(self):
        self.temp.cleanup()

    def run_tool(self, *args, policy=None):
        command = [sys.executable, "-I", TOOL, "--policy", policy or self.policy, "--dir", self.dir]
        return subprocess.run(command + list(args), stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              universal_newlines=True)

    def generate(self):
        result = self.run_tool()
        self.assertEqual(result.returncode, 0, result.stderr)
        return read(self.output)

    def test_generation_passes_and_check_is_clean_on_committed_output(self):
        # The committed block is built from the real notes and section list, not this class's stubs.
        for name in ("PLATFORM.md", "policy.sections"):
            shutil.copyfile(os.path.join(REAL_DIR, name), os.path.join(self.dir, name))
        generated = self.generate()
        committed = read(os.path.join(REAL_DIR, "AGENTS.kit.md"))
        self.assertEqual(generated, committed)
        self.assertEqual(self.run_tool("--check").returncode, 0)
        real_check = subprocess.run([sys.executable, "-I", TOOL, "--check"], stdout=subprocess.PIPE,
                                    stderr=subprocess.PIPE, universal_newlines=True)
        self.assertEqual(real_check.returncode, 0, real_check.stdout + real_check.stderr)

    def test_missing_heading_fails(self):
        write(os.path.join(self.dir, "policy.sections"), SECTIONS + "## No such heading\n")
        result = self.run_tool()
        self.assertEqual(result.returncode, 1)
        self.assertIn("heading not in POLICY.md", result.stderr)
        self.assertIn("No such heading", result.stderr)
        self.assertFalse(os.path.exists(self.output))

    def test_oversize_output_fails(self):
        write(os.path.join(self.dir, "PLATFORM.md"), "# Title\n\n" + "x" * 17000 + "\n")
        result = self.run_tool()
        self.assertEqual(result.returncode, 1)
        self.assertIn("16384 byte limit", result.stderr)
        self.assertFalse(os.path.exists(self.output))

    def test_hand_edited_output_fails_check(self):
        text = self.generate()
        lines = text.split("\n")
        lines.insert(1, "hand edit")
        write(self.output, "\n".join(lines))
        result = self.run_tool("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("line 2", result.stdout)
        self.assertIn("hand edit", result.stdout)

    def test_check_fails_when_output_is_missing(self):
        result = self.run_tool("--check")
        self.assertEqual(result.returncode, 1)
        self.assertIn("missing", result.stdout)

    def test_version_line_matches_policy(self):
        text = self.generate()
        policy_line = read(self.policy).split("\n")[2]
        match = re.search(r"(\d{4}-\d{2}-\d{2}\.\d+)", policy_line)
        self.assertIsNotNone(match, policy_line)
        version = match.group(1)
        self.assertEqual(text.split("\n")[0], "<!-- Claude Usage Optimizer {} for Codex CLI; generated by "
                         "tools/make-platform-policy.py from POLICY.md; do not edit -->".format(version))

    def test_version_line_follows_a_changed_policy(self):
        text = re.sub(r"version: \d{4}-\d{2}-\d{2}\.\d+\.", "version: 2099-01-01.7.", read(self.policy), count=1)
        write(self.policy, text)
        generated = self.generate()
        self.assertTrue(generated.startswith("<!-- Claude Usage Optimizer 2099-01-01.7 for Codex CLI;"))

    def test_index_lists_every_other_section_once(self):
        generated = self.generate()
        policy_headings = [line[3:] for line in read(self.policy).split("\n") if line.startswith("## ")]
        listed = {"Routing, in order", "Invariants (every lane)", "Briefs", "Data"}
        index = generated.split("## The rest of the policy\n", 1)[1]
        for heading in policy_headings:
            count = index.count("- " + heading + ": read that section of")
            self.assertEqual(count, 0 if heading in listed else 1, heading)

    def test_listed_sections_are_copied_verbatim(self):
        generated = self.generate()
        policy = read(self.policy)
        for heading in ("## Routing, in order", "## Invariants (every lane)", "## Briefs", "## Data"):
            start = policy.index(heading + "\n")
            end = policy.index("\n## ", start + 1) + 1
            self.assertIn(policy[start:end], generated)


if __name__ == "__main__":
    unittest.main()
